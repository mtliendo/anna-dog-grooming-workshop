import { neon } from "@neondatabase/serverless";

/**
 * Hosted deployments only (e.g. Vercel, where the local SQLite file can't persist).
 * Set DATABASE_URL to a Neon Postgres URL; the workshop itself never needs this.
 * Exposes the small part of the libsql client API that lib/db.ts uses.
 */
export type DbClient = {
  execute(query: { sql: string; args: unknown[] } | string): Promise<{ rows: unknown[] }>;
  executeMultiple(sql: string): Promise<void>;
};

export const POSTGRES_SCHEMA = `
  CREATE TABLE IF NOT EXISTS dogs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_sub TEXT NOT NULL,
    name TEXT NOT NULL,
    breed TEXT NOT NULL,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
  );
  CREATE TABLE IF NOT EXISTS appointments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_sub TEXT NOT NULL,
    dog_id INTEGER NOT NULL REFERENCES dogs(id),
    service_id TEXT NOT NULL,
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    calendar_event_id TEXT,
    calendar_event_link TEXT
  );
  CREATE INDEX IF NOT EXISTS idx_dogs_user ON dogs(user_sub);
  CREATE INDEX IF NOT EXISTS idx_appointments_user ON appointments(user_sub)
`;

/** Rewrites SQLite `?` placeholders to Postgres `$1, $2, ...`. */
export function toPostgresPlaceholders(sql: string): string {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

export function createPostgresClient(url: string): DbClient {
  const sql = neon(url);
  return {
    async execute(query) {
      const { sql: text, args } =
        typeof query === "string" ? { sql: query, args: [] } : query;
      const rows = await sql.query(toPostgresPlaceholders(text), args);
      return { rows: rows as unknown[] };
    },
    async executeMultiple(statements) {
      for (const statement of statements.split(";")) {
        if (statement.trim()) await sql.query(statement);
      }
    },
  };
}
